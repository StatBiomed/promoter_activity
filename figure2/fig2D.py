#!/usr/bin/env python3
"""Plot Human Major and Minor TSS regions as TWO separate final-size PDFs.

Python >=3.9, matplotlib, numpy. No imports from other project scripts.
Uses the existing row-level region annotation and counts tables, without
reclassifying or filtering promoters. Both tables are read-only. Every source
field is cross-checked against the step-3 age table before plotting, and the
counts/percentages are independently recomputed from the annotation rows.

Inherited region definition: GRCh37.75; 1-based inclusive TSS on either strand;
all same-gene/chromosome/strand transcripts; strand-aware UTRs outside CDS plus
start/stop codon bounds; introns from individual transcripts, then pooled;
priority 5UTR > 3UTR > Intron > Exon > Unassigned. Exon is a residual label, not
necessarily CDS. These annotations are reused, NOT regenerated by this script.

Denominator: all promoters in each age x class group, including Unassigned.
SP and MP genes are included. The inherited Major/Minor and age labels remain
unchanged. 'Human' means no mapping detected in five target species; it is not
proof of human-specific origin. n is a promoter count, not replicate count.
Descriptive 100% stacks: no error bars, significance tests or causal claims.

final-figure-small: 5 x 4 inches; ticks 12 pt; axis labels 14 pt; legend 12 pt;
editable TrueType text. Only the two PDFs are written, never a combined figure,
PNG/SVG, new data table, or metadata sidecar. Provenance/checks go to stdout.

Usage:
  python3 plot_human_tss_regions_by_age.py --check-only
  python3 plot_human_tss_regions_by_age.py
  python3 plot_human_tss_regions_by_age.py --overwrite
  python3 plot_human_tss_regions_by_age.py --self-test
"""
from __future__ import annotations

import argparse
from collections import Counter
import csv
from decimal import Decimal
import hashlib
import json
import math
import os
from pathlib import Path
import re
import tempfile

BASE = Path('/mnt/ruiyanhou/nfs_share2/proactiv_redo')
AGES = ('Amniote_conserved', 'Eutherian_conserved', 'Primate_restricted', 'Human_specific')
AGE_LABELS = ('Amniote', 'Eutherian', 'Primate', 'Human')
KINDS = ('Major', 'Minor')
REGIONS = ('5UTR', '3UTR', 'Intron', 'Exon', 'Unassigned')
REGION_LABELS = dict(zip(REGIONS, ("5'UTR", "3'UTR", 'Intron', 'Exon', 'Unassigned')))
COLORS = dict(zip(REGIONS, ('#FBB463', '#80B1D3', '#F47F72', '#BDBADB', '#BBBBBB')))
OUTPUT_NAMES = ('Human_major_TSS_regions_by_age.pdf', 'Human_minor_TSS_regions_by_age.pdf')


def require(condition, message):
    if not condition:
        raise ValueError(message)


def checksum(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def read_tsv(path, required):
    with Path(path).open(encoding='utf-8-sig', newline='') as handle:
        reader = csv.DictReader(handle, delimiter='\t')
        fields = reader.fieldnames or []
        rows = list(reader)
    require(rows and required <= set(fields), f'Empty table or missing columns: {path}')
    require(len(fields) == len(set(fields)), f'Duplicate column names: {path}')
    require(all(None not in r and all(v is not None for v in r.values()) for r in rows),
            f'Malformed TSV rows: {path}')
    return fields, rows


def promoter_key(row):
    match = re.fullmatch(r'(?:promoter_)?([0-9]+)', row['promoterId'].strip())
    require(match is not None, f"Invalid promoterId: {row['promoterId']}")
    return int(match.group(1))


def index_rows(rows):
    result = {}
    for row in rows:
        key = promoter_key(row)
        require(key not in result, f'Duplicate promoterId: {key}')
        result[key] = row
    return result


def summarize(rows):
    counts, totals = Counter(), Counter()
    for row in rows:
        age, kind, region = row['TSS_age_group'], row['promoter_class'], row['assigned_region']
        require(age in AGES and kind in KINDS and region in REGIONS, 'Unknown age/class/region')
        counts[age, kind, region] += 1
        totals[age, kind] += 1
    for age in AGES:
        for kind in KINDS:
            require(totals[age, kind] > 0, f'Empty age/class group: {age}, {kind}')
            require(sum(counts[age, kind, r] for r in REGIONS) == totals[age, kind], 'Denominator mismatch')
    return counts, totals


def load_and_validate(annotation, counts_table, source):
    required = {'promoterId', 'geneId', 'promoter_class', 'TSS_age_group', 'TSS_age_label',
                'internalPromoter', 'mean_promoter_activity', 'start', 'strand', 'seqnames'}
    fields, rows = read_tsv(annotation, required | {'assigned_region'})
    source_fields, source_rows = read_tsv(source, required)
    indexed, originals = index_rows(rows), index_rows(source_rows)
    require(set(indexed) == set(originals), 'Annotation and current age input have different promoter sets')
    require(set(source_fields) <= set(fields), 'Annotation lost source columns')
    gene_counts, major_counts = Counter(), Counter()
    for pid, row in indexed.items():
        require(all(row[f] == originals[pid][f] for f in source_fields), f'Changed source field for promoter {pid}')
        require(row['internalPromoter'].strip().upper() in {'FALSE', 'F', '0'}, 'Internal promoter present')
        activity = Decimal(row['mean_promoter_activity'])
        require(activity.is_finite() and activity > 0, 'Nonpositive or nonfinite activity present')
        require(row['TSS_age_group'] in AGES, 'Unknown age group')
        require(row['TSS_age_label'] == AGE_LABELS[AGES.index(row['TSS_age_group'])], 'Age label mismatch')
        require(row['geneId'].strip() not in {'', '.', 'NA'}, 'Missing geneId')
        gene_counts[row['geneId']] += 1
        major_counts[row['geneId']] += row['promoter_class'] == 'Major'
    require(all(major_counts[g] == 1 for g in gene_counts), 'Expected exactly one Major per gene')
    counts, totals = summarize(rows)
    _, stored = read_tsv(counts_table, {'TSS_age_group', 'TSS_age_label', 'promoter_class', 'region', 'count', 'total', 'percent'})
    expected_keys = {(a, k, r) for a in AGES for k in KINDS for r in REGIONS}
    seen = set()
    for record in stored:
        age, kind, region = record['TSS_age_group'], record['promoter_class'], record['region']
        key = age, kind, region
        require(key in expected_keys and key not in seen, 'Unexpected or duplicate counts-table row')
        seen.add(key)
        require(record['TSS_age_label'] == AGE_LABELS[AGES.index(age)], 'Counts age label mismatch')
        require(int(record['count']) == counts[key], f'Count mismatch: {key}')
        require(int(record['total']) == totals[age, kind], f'Total mismatch: {key}')
        require(math.isclose(float(record['percent']), 100 * counts[key] / totals[age, kind], abs_tol=1e-10, rel_tol=0),
                f'Percentage mismatch: {key}')
    require(seen == expected_keys, 'Counts table is incomplete')
    print(f'Validated {len(rows):,} promoters / {len(gene_counts):,} genes; all source fields and 40 count rows agree.', flush=True)
    for kind in KINDS:
        print(kind, {label: totals[age, kind] for age, label in zip(AGES, AGE_LABELS)}, flush=True)
    return counts, totals


def build_figure(counts, totals, kind):
    require(kind in KINDS, 'A figure must be either Major or Minor; no combined mode exists')
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    from matplotlib.text import Text
    import numpy as np

    # Equivalent to the bundled final-figure-small helper; keep this script standalone.
    plt.rcParams.update({'font.family': 'DejaVu Sans', 'pdf.fonttype': 42,
                         'axes.spines.top': False, 'axes.spines.right': False,
                         'axes.linewidth': .8, 'legend.frameon': False,
                         'xtick.labelsize': 12, 'ytick.labelsize': 12,
                         'axes.labelsize': 14, 'legend.fontsize': 12})
    fig, ax = plt.subplots(figsize=(5, 4))
    fig.subplots_adjust(left=.18, right=.985, bottom=.17, top=.715)
    x = np.arange(len(AGES))
    bottom = np.zeros(len(AGES))
    regions = list(REGIONS[:-1])
    if any(counts[a, k, 'Unassigned'] for a in AGES for k in KINDS):
        regions.append('Unassigned')
    for region in regions:
        height = np.array([100 * counts[a, kind, region] / totals[a, kind] for a in AGES])
        ax.bar(x, height, bottom=bottom, width=.68, color=COLORS[region],
               edgecolor='white', linewidth=.6, label=REGION_LABELS[region])
        bottom += height
    require(np.allclose(bottom, 100, atol=1e-10, rtol=0), 'Stacks must sum to 100%')
    ax.set_ylim(0, 100)
    ax.set_xlim(-.6, 3.6)
    ax.set_yticks([0, 25, 50, 75, 100])
    ax.set_xticks(x, AGE_LABELS)
    ax.set_ylabel('Proportion (%)', fontsize=14)
    ax.tick_params(axis='x', labelsize=12, length=0, pad=7)
    ax.tick_params(axis='y', labelsize=12)
    ax.grid(False)
    for position, age in zip(x, AGES):
        ax.annotate(f'n={totals[age, kind]:,}', (position, 100), xytext=(0, 5),
                    textcoords='offset points', ha='center', va='bottom', fontsize=9.5,
                    annotation_clip=False)
    title = fig.text(.58, .978, f'{kind} promoters', ha='center', va='top', fontsize=14)
    legend = fig.legend(*ax.get_legend_handles_labels(), loc='upper center',
                        bbox_to_anchor=(.58, .935), ncol=2 if len(regions) == 4 else 3,
                        fontsize=12, columnspacing=1.2, handlelength=1.1, handletextpad=.6)
    fig.text(.18, .035, "'Human': no mapping detected in five target species.", fontsize=6.7)
    fig.canvas.draw()
    renderer = fig.canvas.get_renderer()
    texts = [t for t in fig.findobj(Text) if t.get_visible() and t.get_text()]
    for text in texts:
        box = text.get_window_extent(renderer)
        require(box.x0 >= -1 and box.y0 >= -1 and box.x1 <= fig.bbox.width + 1 and box.y1 <= fig.bbox.height + 1,
                f'Text outside 5 x 4 inch canvas: {text.get_text()}')
    legend_box = legend.get_window_extent(renderer)
    require(not title.get_window_extent(renderer).overlaps(legend_box), 'Title overlaps legend')
    for text in ax.texts:
        require(not text.get_window_extent(renderer).overlaps(legend_box), 'Legend overlaps sample-size labels')
    for group in (ax.get_xticklabels(), ax.texts):
        for i, left in enumerate(group):
            for right in group[i + 1:]:
                require(not left.get_window_extent(renderer).overlaps(right.get_window_extent(renderer)), 'Labels overlap')
    return fig


def self_test():
    synthetic = [{'TSS_age_group': a, 'promoter_class': k, 'assigned_region': r}
                 for a in AGES for k in KINDS for r in ('5UTR', 'Unassigned')]
    counts, totals = summarize(synthetic)
    require(all(v == 2 for v in totals.values()), 'Unassigned dropped from denominator')
    require(all(counts[a, k, 'Unassigned'] == 1 for a in AGES for k in KINDS), 'Unassigned count wrong')
    try:
        index_rows([{'promoterId': '01'}, {'promoterId': 'promoter_1'}])
    except ValueError:
        pass
    else:
        raise AssertionError('Duplicate normalized promoter ID was accepted')
    import matplotlib.pyplot as plt
    for kind in KINDS:
        fig = build_figure(counts, totals, kind)
        require(list(fig.get_size_inches()) == [5, 4], 'Wrong physical figure size')
        plt.close(fig)
    try:
        build_figure(counts, totals, None)
    except ValueError:
        pass
    else:
        raise AssertionError('Combined plot mode was accepted')
    print('SELF-TEST PASSED: group counts, Unassigned denominators, duplicate IDs, layout, separate-only figures.')


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--annotation', type=Path, default=BASE / '4.get_character/Human_major_minor_TSS_region_annotation.tsv')
    parser.add_argument('--counts', type=Path, default=BASE / '4.get_character/Human_major_minor_TSS_region_counts.tsv')
    parser.add_argument('--source', type=Path, default=BASE / '3.get_promoter_age/Human_major_minor_promoters_with_age.tsv')
    parser.add_argument('--outdir', type=Path, default=Path(__file__).resolve().parent)
    parser.add_argument('--check-only', action='store_true')
    parser.add_argument('--self-test', action='store_true')
    parser.add_argument('--overwrite', action='store_true', help='Replace only the two named PDFs')
    args = parser.parse_args()
    if args.self_test:
        self_test()
        return
    inputs = (args.annotation, args.counts, args.source)
    hashes = {str(p.resolve()): checksum(p) for p in inputs}
    counts, totals = load_and_validate(*inputs)
    if args.check_only:
        print('CHECK PASSED; no files written.')
        return
    targets = [args.outdir / name for name in OUTPUT_NAMES]
    require(all(not p.is_symlink() for p in targets), 'Refusing symlink output target')
    require(all(p.resolve() not in hashes for p in targets), 'Output conflicts with input')
    require(args.overwrite or not any(p.exists() for p in targets), 'PDFs exist; use --overwrite or a different --outdir')
    args.outdir.mkdir(parents=True, exist_ok=True)
    import matplotlib.pyplot as plt
    with tempfile.TemporaryDirectory(prefix='.separate_regions_', dir=args.outdir) as temporary:
        staged = [Path(temporary) / name for name in OUTPUT_NAMES]
        for kind, path in zip(KINDS, staged):
            fig = build_figure(counts, totals, kind)
            fig.savefig(path, format='pdf', facecolor='white', metadata={
                'Title': f'Human {kind} promoter TSS regions by mapping-based age',
                'Subject': 'Each age/class denominator includes all promoters; inherited annotations unchanged; descriptive proportions.',
                'Keywords': '5 x 4 inches; 12 pt ticks/legend; 14 pt axis label; SP and MP included; Human is no mapping detected; Exon is not necessarily CDS.',
                'CreationDate': None, 'ModDate': None})
            plt.close(fig)
        require(hashes == {str(p.resolve()): checksum(p) for p in inputs}, 'Input changed during run')
        for src, dst in zip(staged, targets):
            require(not dst.is_symlink() and (args.overwrite or not dst.exists()), 'Output appeared during run')
            os.replace(src, dst)
    print(json.dumps({'input_sha256': hashes, 'output_sha256': {str(p): checksum(p) for p in targets},
                      'figure_size_inches': [5, 4], 'combined_figure': False, 'checks': 'passed'}, indent=2))


if __name__ == '__main__':
    main()
